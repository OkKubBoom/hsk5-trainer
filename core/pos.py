"""ชนิดของคำ — แปลงแท็กในฐานข้อมูลเป็นตัวย่อภาษาไทยที่แสดงหลังคำ

ผู้ใช้ขอมาเอง: "อยากให้เพิ่มชนิดของคำศัพท์ เช่นคำนี้คือกริยา นาม หรือสรรพนาม
เป็นตัวย่อหลังคำก็ได้"

**ทำไมสำคัญกว่าที่คิด** — ภาษาจีนไม่ผันรูปตามชนิดคำ 影响 เป็นได้ทั้งกริยาและนาม
โดยหน้าตาไม่เปลี่ยนเลย ผู้เรียนไทยจึงเดาจากรูปคำไม่ได้เหมือนภาษาอังกฤษ
และข้อ 完成句子 (เรียงคำ) ตัดสินถูกผิดที่ชนิดคำล้วนๆ

ข้อมูลมีอยู่ในฐานแล้วที่ `VocabItem.tags` แค่ไม่เคยเอามาแสดง

⚠️ แท็กพวกนี้มาจากการนำเข้าอัตโนมัติ ยังไม่มีครูตรวจ เหมือนคำแปล
"""
from __future__ import annotations

# แท็ก → (ตัวย่อ, ชื่อเต็มไทย)
# เรียงตามลำดับที่อยากให้แสดงเมื่อคำหนึ่งมีหลายชนิด — คำจีนเป็นได้หลายชนิดบ่อยมาก
POS = [
    ("v",     ("ก.",     "คำกริยา 动词")),
    ("n",     ("น.",     "คำนาม 名词")),
    ("adj",   ("คุณ.",   "คำคุณศัพท์ 形容词")),
    ("adv",   ("ว.",     "คำวิเศษณ์ 副词")),
    ("pron",  ("สรรพ.",  "คำสรรพนาม 代词")),
    ("m",     ("ลก.",    "ลักษณนาม 量词")),
    ("num",   ("จำนวน", "คำบอกจำนวน 数词")),
    ("conj",  ("สัน.",   "คำสันธาน 连词")),
    ("conn",  ("เชื่อม", "คำเชื่อมประโยค")),
    ("prep",  ("บุพ.",   "คำบุพบท 介词")),
    ("part",  ("เสริม",  "คำเสริม 助词")),
    ("idiom", ("สำนวน", "สำนวน 成语")),
    ("time",  ("เวลา",   "คำบอกเวลา")),
]

# แท็กที่สะกดไม่ตรงกันจากการนำเข้าคนละรอบ — รวมให้เป็นอันเดียวตอนอ่าน
# ไม่ไปแก้ในฐาน เพราะการเขียนทับ tags เคยทำ human_verified หายมาแล้ว (1.14.1)
ALIASES = {"verb": "v", "noun": "n", "number": "num", "adjective": "adj",
           "adverb": "adv", "pronoun": "pron", "measure": "m"}

_ORDER = {tag: i for i, (tag, _) in enumerate(POS)}
_LABEL = dict(POS)


def of(vocab) -> list[dict]:
    """ชนิดของคำนี้ เรียงตามลำดับใน POS — คืน [] ถ้าไม่มีแท็กชนิดคำเลย

    คืนหลายชนิดได้ตามจริง ไม่เลือกมาอันเดียว เพราะการบอกว่า 影响 เป็น "กริยา"
    อย่างเดียวคือข้อมูลผิด และผู้เรียนจะเรียงประโยคผิดตามที่เราบอก
    """
    # รับได้ทั้ง VocabItem และ dict จาก .values() — listen_explain ส่ง dict มา
    if isinstance(vocab, dict):
        tags = vocab.get("tags") or []
    else:
        tags = getattr(vocab, "tags", None) or []
    seen = []
    for raw in tags:
        tag = ALIASES.get(raw, raw)
        if tag in _LABEL and tag not in seen:
            seen.append(tag)
    # conn เป็นหมวดของเราเอง (หน้าคำเชื่อม) ไม่ใช่ชนิดคำคนละตัวกับ conj
    # ถ้ามีทั้งคู่จะได้ "สัน. · เชื่อม" ซึ่งอ่านแล้วเหมือนเป็นสองชนิด
    if "conj" in seen and "conn" in seen:
        seen.remove("conn")
    seen.sort(key=lambda t: _ORDER[t])
    return [{"tag": t, "short": _LABEL[t][0], "full": _LABEL[t][1]} for t in seen]


def short(vocab) -> str:
    """ตัวย่อรวมบรรทัดเดียว เช่น "ก. · น." — ว่างถ้าไม่รู้ชนิด"""
    return " · ".join(p["short"] for p in of(vocab))


def title(vocab) -> str:
    """ข้อความเต็มสำหรับ tooltip"""
    return " · ".join(p["full"] for p in of(vocab))
